// 中文朗读的多音字修正。
//
// 为什么需要：TTS 引擎（安卓原生语音 / 浏览器 speechSynthesis）都按现代汉语习惯选音，
// 古诗、儿歌里的古音常被读错——「白日依山尽」的「尽」应读 jìn（到头了），
// 引擎却按常用音读成 jǐn（尽力）。
//
// 引擎没有暴露拼音或音素接口（speechSynthesis 也不支持 SSML 的 phoneme），
// 所以只能在「送给引擎的文本」上做手脚：把那个字换成同音、而且只有一个读音的字，
// 引擎就一定会按正确的音念出来。例：尽 → 进（jìn）、处 → 触（chù）、数 → 鼠（shǔ）。
//
// 重要：只改送给 TTS 的文本，屏幕上的原文、逐句高亮、内容文件都不受影响。
//
// 怎么判断该读哪个音：
//   1. 古诗按教材/古诗传统读音（尽 jìn、处 chù、泊 bó、斜 xiá、骑 qí）；
//   2. 儿歌、故事按现代汉语词典的常用音；
//   3. 只写「例外」——引擎本来就读对的词不写进来，避免把对的改成错的。
//   规则按词组写（山尽、处处），不要按单字写，否则会误伤现代词（如「重要」「长大」）。

