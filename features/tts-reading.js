/**
 * 把文本改成「TTS 读得对」的版本：按规则做同音字替换。
 * 纯函数，不改原字符串。
 */
export function applyTtsReading(text) {
  let output = String(text ?? '');
  if (!output) return output;
  for (const rule of TTS_READING_RULES) {
    if (output.includes(rule.from)) output = output.split(rule.from).join(rule.to);
  }
  return output;
}

